class HybridTaxRetriever:
    """
    Hybrid Retriever supporting:
    1. Lexical BM25/Keyword Token Overlap (Zero-latency offline mode)
    2. Dense Vector Store Interface (Qdrant / Chroma integration layer as proposed in project proposal)
    """
    def __init__(self, docs=None, use_vector_db: bool = False):
        self.docs = docs or TAX_KNOWLEDGE_DOCS
        self.use_vector_db = use_vector_db

    def retrieve(self, query: str, top_k: int = 2) -> list:
        q = query.lower()
        scores = []

        for doc in self.docs:
            score = 0
            for kw in doc["keywords"]:
                if len(kw) <= 4:
                    hit = re.search(r"(?<![\w\u0980-\u09FF])" + re.escape(kw) + r"(?![\w\u0980-\u09FF])", q) is not None
                else:
                    hit = kw in q
                if hit:
                    score += 3
            for word in doc["category"].lower().split():
                if len(word) > 2 and word in q:
                    score += 2
            scores.append((score, doc))

        scores.sort(key=lambda x: x[0], reverse=True)
        valid_results = [item[1] for item in scores if item[0] >= 3]
        if not valid_results:
            return [{
                "id": "not_confident",
                "category": "সাধারণ তথ্য",
                "sections": ["General Guidance"],
                "title": "সুনির্দিষ্ট কোনো ধারা পাওয়া যায়নি",
                "snippet": "আপনার প্রশ্নের বিষয়টি আয়কর আইনের সুনির্দিষ্ট ধারাগুলোর সাথে পুরোপুরি মেলেনি।",
                "content": "আমি আপনার প্রশ্নের সুনির্দিষ্ট আইনি ধারা খুঁজে পাইনি। অনুগ্রহ করে বিস্তারিত বা স্পষ্ট করে বলুন।"
            }]
        return valid_results[:top_k]


# Default singleton retriever instance
